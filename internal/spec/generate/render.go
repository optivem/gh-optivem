package generate

import (
	"fmt"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

// UntaggedFeature is the Feature name of the trailing block of tests that
// carry no criterion ID.
const UntaggedFeature = "Untagged acceptance tests"

// Feature is one use case's block in the output.
type Feature struct {
	ID    string // UC-NNN; "" for the untagged block
	Title string
}

// Render writes the Gherkin document for cases. titles maps a use-case ID to
// its title; every criterion's use case must be in it (Generate checks this).
// Each scenario carries exactly one criterion tag: a test with several IDs is
// emitted once under each. Untagged tests go into a trailing block.
func Render(cases []TestCase, titles map[string]string, sources []string) string {
	type entry struct {
		id string
		tc TestCase
	}
	byUC := map[string][]entry{}
	var untagged []TestCase
	for _, tc := range cases {
		if len(tc.Tags) == 0 {
			untagged = append(untagged, tc)
			continue
		}
		for _, id := range tc.Tags {
			uc := useCaseOf(id)
			byUC[uc] = append(byUC[uc], entry{id, tc})
		}
	}
	ucs := make([]string, 0, len(byUC))
	for uc := range byUC {
		ucs = append(ucs, uc)
	}
	sort.Slice(ucs, func(i, j int) bool { return idLess(ucs[i], ucs[j]) })

	var b strings.Builder
	b.WriteString("# Generated by `gh optivem spec generate` from acceptance-test sources. Do not commit.\n")
	b.WriteString("# Sources: " + strings.Join(sources, ", ") + "\n")
	for _, uc := range ucs {
		es := byUC[uc]
		sort.SliceStable(es, func(i, j int) bool {
			if es[i].id != es[j].id {
				return idLess(es[i].id, es[j].id)
			}
			return caseLess(es[i].tc, es[j].tc)
		})
		fmt.Fprintf(&b, "\nFeature: %s %s\n", uc, titles[uc])
		for _, e := range es {
			writeScenario(&b, e.tc, "@"+e.id)
		}
	}
	if len(untagged) > 0 {
		sort.SliceStable(untagged, func(i, j int) bool { return caseLess(untagged[i], untagged[j]) })
		fmt.Fprintf(&b, "\nFeature: %s\n", UntaggedFeature)
		for _, tc := range untagged {
			writeScenario(&b, tc, "")
		}
	}
	return b.String()
}

func caseLess(a, b TestCase) bool {
	if a.File != b.File {
		return a.File < b.File
	}
	return a.Line < b.Line
}

func useCaseOf(id string) string {
	uc, _, _ := strings.Cut(id, ".")
	return uc
}

// idLess orders UC-NNN and UC-NNN.M IDs numerically.
func idLess(a, b string) bool {
	na, nb := idNumbers(a), idNumbers(b)
	for i := 0; i < len(na) && i < len(nb); i++ {
		if na[i] != nb[i] {
			return na[i] < nb[i]
		}
	}
	return len(na) < len(nb)
}

func idNumbers(id string) []int {
	var out []int
	for _, p := range strings.Split(strings.TrimPrefix(id, "UC-"), ".") {
		n, _ := strconv.Atoi(p)
		out = append(out, n)
	}
	return out
}

func writeScenario(b *strings.Builder, tc TestCase, tag string) {
	tags := tag
	if tc.Wip {
		tags = strings.TrimSpace(tags + " @wip")
	}
	b.WriteString("\n")
	if tags != "" {
		b.WriteString("  " + tags + "\n")
	}
	kind := "Scenario"
	if len(tc.Params) > 0 {
		kind = "Scenario Outline"
	}
	fmt.Fprintf(b, "  %s: %s\n", kind, sentence(humanize(tc.Name)))
	for _, l := range stepLines(tc.Sections) {
		b.WriteString("    " + l + "\n")
	}
	if len(tc.Params) == 0 {
		return
	}
	b.WriteString("\n")
	if tc.Examples.Source != "" {
		fmt.Fprintf(b, "    # Examples: supplied by %s\n", tc.Examples.Source)
		return
	}
	b.WriteString("    Examples:\n")
	writeTable(b, append([][]string{tc.Params}, tc.Examples.Rows...))
}

func writeTable(b *strings.Builder, rows [][]string) {
	widths := make([]int, len(rows[0]))
	cells := make([][]string, len(rows))
	for r, row := range rows {
		cells[r] = make([]string, len(row))
		for c, v := range row {
			v = strings.ReplaceAll(v, "|", `\|`)
			if v == "" {
				v = `""`
			}
			cells[r][c] = v
			widths[c] = max(widths[c], len([]rune(v)))
		}
	}
	for _, row := range cells {
		b.WriteString("      |")
		for c, v := range row {
			b.WriteString(" " + v + strings.Repeat(" ", widths[c]-len([]rune(v))) + " |")
		}
		b.WriteString("\n")
	}
}

// stepLines applies the mapping rules: a given/when section is one line (its
// subject then its comma-joined modifiers); a then section's subject is one
// line and each assertion is its own And line, prefixed by the entity it is
// called on when the section was opened with .and().
func stepLines(sections []Section) []string {
	var lines []string
	for _, s := range sections {
		lead := map[string]string{KeywordGiven: "Given", KeywordWhen: "When", KeywordThen: "Then"}[s.Keyword]
		if s.Continuation {
			lead = "And"
		}
		subject := callProse(s.Subject)
		switch s.Keyword {
		case KeywordGiven, KeywordWhen:
			if s.Keyword == KeywordGiven {
				subject = article(s.Subject.Name) + subject
			}
			line := lead + " " + subject
			if len(s.Modifiers) > 0 {
				mods := make([]string, len(s.Modifiers))
				for i, m := range s.Modifiers {
					mods[i] = callProse(m)
				}
				line += " " + strings.Join(mods, ", ")
			}
			lines = append(lines, line)
		case KeywordThen:
			if !s.Continuation {
				lines = append(lines, lead+" "+subject)
				for _, m := range s.Modifiers {
					lines = append(lines, "And "+callProse(m))
				}
				continue
			}
			if len(s.Modifiers) == 0 {
				lines = append(lines, "And "+subject)
			}
			for _, m := range s.Modifiers {
				lines = append(lines, "And "+subject+" "+callProse(m))
			}
		}
	}
	return lines
}

func callProse(c Call) string {
	s := humanize(c.Name)
	if len(c.Args) == 0 {
		return s
	}
	args := make([]string, len(c.Args))
	for i, a := range c.Args {
		args[i] = argText(a)
	}
	return s + " " + strings.Join(args, ", ")
}

func argText(a Arg) string {
	switch a.Kind {
	case ArgString, ArgTemplate:
		return `"` + a.Text + `"`
	case ArgParam:
		return "<" + a.Text + ">"
	}
	return a.Text
}

// humanize splits an identifier on case boundaries, digits and underscores and
// lowercases the words; all-caps runs (acronyms such as ORD, SKU) keep their
// case.
func humanize(name string) string {
	var words []string
	rs := []rune(name)
	start := 0
	flush := func(end int) {
		if end > start {
			words = append(words, string(rs[start:end]))
		}
		start = end
	}
	for i := 0; i < len(rs); i++ {
		r := rs[i]
		if r == '_' || r == '-' || r == ' ' {
			flush(i)
			start = i + 1
			continue
		}
		if i == start {
			continue
		}
		prev := rs[i-1]
		switch {
		case unicode.IsUpper(r) && unicode.IsLower(prev),
			unicode.IsUpper(r) && unicode.IsDigit(prev),
			unicode.IsDigit(r) && unicode.IsLetter(prev),
			unicode.IsUpper(r) && unicode.IsUpper(prev) && i+1 < len(rs) && unicode.IsLower(rs[i+1]):
			flush(i)
		}
	}
	flush(len(rs))
	for i, w := range words {
		if !isAcronym(w) {
			words[i] = strings.ToLower(w)
		}
	}
	return strings.Join(words, " ")
}

func isAcronym(w string) bool {
	letters := 0
	for _, r := range w {
		if unicode.IsLower(r) {
			return false
		}
		if unicode.IsLetter(r) {
			letters++
		}
	}
	return letters >= 2
}

func sentence(s string) string {
	if s == "" {
		return s
	}
	rs := []rune(s)
	rs[0] = unicode.ToUpper(rs[0])
	return string(rs)
}

// article returns the indefinite article for a Given subject: "a "/"an " for
// a one-word subject (a noun such as product, order), nothing for a
// multi-word one (a state such as loggedInAsCustomer).
func article(name string) string {
	w := humanize(name)
	if strings.Contains(w, " ") || w == "" {
		return ""
	}
	if strings.ContainsRune("aeiouAEIOU", rune(w[0])) {
		return "an "
	}
	return "a "
}
